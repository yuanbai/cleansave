/** A translatable UI string identifier. */
export type MessageKey = keyof typeof messages;

/** Resolve a UI string identifier in the selected language. */
export type Translate = (key: MessageKey) => string;

/**
 * Return a translator for Simplified Chinese, falling back to English for other language values.
 */
export function translator(language: string): Translate {
  return (key) => messages[key][language === 'zh-CN' ? 1 : 0];
}
